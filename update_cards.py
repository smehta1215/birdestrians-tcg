#!/usr/bin/env python3
"""Scans the cards/ folder and writes cards/cards.js, which the app reads.

Run this every time you add, remove or rename a card image:

    python3 update_cards.py

File-name rules (case-insensitive):
  * Cards are shown in file-name order, so prefix them: 01-..., 02-..., 03-...
  * Put "holo" anywhere in the name to give the card the holographic shimmer.
  * Put "gift" anywhere in the name to make it the grand-finale gift card.
    It is always shown last, face-down, and flipped with confetti.
Supported formats: .png .jpg .jpeg .webp .gif .svg
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
CARDS_DIR = os.path.join(ROOT, "cards")
EXTS = (".png", ".jpg", ".jpeg", ".webp", ".gif", ".svg")


def natural_key(name):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", name)]


def main():
    files = sorted((f for f in os.listdir(CARDS_DIR) if f.lower().endswith(EXTS)), key=natural_key)
    cards = []
    for f in files:
        low = f.lower()
        cards.append({"file": "cards/" + f, "holo": "holo" in low, "gift": "gift" in low})
    cards.sort(key=lambda c: c["gift"])  # gift card(s) always last; order is otherwise preserved
    out = os.path.join(CARDS_DIR, "cards.js")
    with open(out, "w") as fh:
        fh.write("// Generated by update_cards.py. Re-run it after changing the cards folder.\n")
        fh.write("window.BIRDESTRIANS_CARDS = " + json.dumps(cards, indent=2) + ";\n")
    print(f"Found {len(cards)} card(s):")
    for c in cards:
        tags = [t for t in ("holo", "gift") if c[t]]
        print("  ", c["file"], f"[{', '.join(tags)}]" if tags else "")


if __name__ == "__main__":
    main()
